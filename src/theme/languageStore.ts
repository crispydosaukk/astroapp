export function translateStringWithDict(text: string, lang: AppLanguage): string {
  if (!text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  const map = TRANSLATIONS[lang];
  if (!map) return text;

  // Direct exact match
  let translated = map[trimmed];

  // Try punctuation-stripped match
  let suffix = '';
  if (!translated && trimmed.length > 2) {
    const lastChar = trimmed[trimmed.length - 1];
    if ([':', '?', '!', '.'].includes(lastChar)) {
      const withoutPunct = trimmed.slice(0, -1).trim();
      if (map[withoutPunct]) {
        translated = map[withoutPunct];
        suffix = lastChar;
      }
    }
  }

  // Try uppercase lookup
  if (!translated) {
    const upper = trimmed.toUpperCase();
    if (map[upper]) {
      translated = map[upper];
    }
  }

  if (translated) {
    const lead = text.match(/^\s*/)?.[0] || '';
    const trail = text.match(/\s*$/)?.[0] || '';
    return `${lead}${translated}${suffix}${trail}`;
  }

  return text;
}

interface LanguageState {
  selectedLanguage: AppLanguage;
  hydrated: boolean;
  load: () => Promise<void>;
  setLanguage: (lang: AppLanguage) => Promise<void>;
  t: (key: string, fallback?: string) => string;
  translateText: (text: string) => string;
}

export const useLanguageStore = create<LanguageState>((set, get) => ({
  selectedLanguage: 'English',
  hydrated: false,

  load: async () => {
    try {
      const stored = await AsyncStorage.getItem(STORAGE_LANG_KEY);
      if (stored && TRANSLATIONS[stored as AppLanguage]) {
        set({ selectedLanguage: stored as AppLanguage, hydrated: true });
      } else {
        set({ hydrated: true });
      }
    } catch {
      set({ hydrated: true });
    }
  },

  setLanguage: async (lang) => {
    set({ selectedLanguage: lang });
    try {
      await AsyncStorage.setItem(STORAGE_LANG_KEY, lang);
    } catch {}
  },

  translateText: (text: string) => {
    const lang = get().selectedLanguage;
    if (lang === 'English') return text;
    return translateStringWithDict(text, lang);
  },

  t: (key: string, fallback?: string) => {
    const lang = get().selectedLanguage;
    if (lang === 'English') return fallback ?? key;
    const map = TRANSLATIONS[lang];
    if (map && map[key]) return map[key];
    if (fallback) {
      const trFallback = translateStringWithDict(fallback, lang);
      if (trFallback !== fallback) return trFallback;
    }
    const trKey = translateStringWithDict(key, lang);
    if (trKey !== key) return trKey;
    return fallback ?? key;
  },
}));

/** Convenient hook for instant translation reactivity */
export function useTranslation() {
  const selectedLanguage = useLanguageStore((s) => s.selectedLanguage);
  const t = useLanguageStore((s) => s.t);
  const translateText = useLanguageStore((s) => s.translateText);
  const setLanguage = useLanguageStore((s) => s.setLanguage);
  return { selectedLanguage, t, translateText, setLanguage };
}
